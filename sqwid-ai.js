  // Нормализация текста: учитывает регистр, ё/е и знаки препинания.
  function normalize(value) {
    return String(value || "")
      .toLowerCase()
      .replace(/ё/g, "е")
      .replace(/[^a-zа-я0-9@+]+/gi, " ")
      .replace(/\s+/g, " ")
      .trim();
  }

  // Расстояние Левенштейна для поиска слов с небольшими опечатками.
  function levenshtein(a, b) {
    if (a === b) return 0;
    if (!a.length) return b.length;
    if (!b.length) return a.length;

    let prev = Array.from({ length: b.length + 1 }, (_, i) => i);

    for (let i = 1; i <= a.length; i++) {
      const current = [i];

      for (let j = 1; j <= b.length; j++) {
        const cost = a[i - 1] === b[j - 1] ? 0 : 1;

        current[j] = Math.min(
          current[j - 1] + 1,
          prev[j] + 1,
          prev[j - 1] + cost
        );
      }

      prev = current;
    }

    return prev[b.length];
  }

  function wordsOf(text) {
    return normalize(text).split(" ").filter(word => word.length > 1);
  }

  function scoreEntry(question, entry) {
    const q = normalize(question);
    const qWords = wordsOf(q);
    let best = 0;

    for (const rawKeyword of entry.keywords) {
      const keyword = normalize(rawKeyword);
      if (!keyword) continue;

      if (q === keyword) {
        best = Math.max(best, 12 + keyword.length / 10);
        continue;
      }

      if (q.includes(keyword)) {
        best = Math.max(best, 9 + keyword.length / 20);
        continue;
      }

      const keywordWords = wordsOf(keyword);
      let matched = 0;

      for (const kw of keywordWords) {
        let wordBest = 0;

        for (const qw of qWords) {
          if (qw === kw) {
            wordBest = 1;
          } else if (qw.length >= 4 && kw.length >= 4) {
            const maxLength = Math.max(qw.length, kw.length);
            const distance = levenshtein(qw, kw);
            const similarity = 1 - distance / maxLength;

            if (similarity >= 0.76) {
              wordBest = Math.max(wordBest, similarity);
            }
          }
        }

        matched += wordBest;
      }

      if (keywordWords.length) {
        const ratio = matched / keywordWords.length;
        best = Math.max(best, ratio * (5 + Math.min(keyword.length / 8, 2)));
      }
    }

    return best;
  }

